    end

    colormap(turbo);

    sgtitle( ...
        sprintf( ...
        'FSST comparison using one physical frame %d', ...
        originalFrameNumber));

end

%% Compare extracted STFT ridges

figure('Color', 'w');

hold on;

for caseIndex = 1:numCases

    plot( ...
        stftResult{caseIndex}.timeMs, ...
        stftResult{caseIndex}.ridgeVelocity, ...
        'LineWidth', 1.5, ...
        'DisplayName', ...
        sprintf('%d Chirps', ...
        windowLengthList(caseIndex)));

end

hold off;

grid on;
box on;

xlabel('Time (ms)');
ylabel('Aliased radial velocity (m/s)');

ylim([0, derived.vMax]);

title('STFT ridge comparison');

legend('Location', 'best');