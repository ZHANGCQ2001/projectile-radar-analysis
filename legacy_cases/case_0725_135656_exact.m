%% =========================================================
%  17. 从所有候选点中筛选连续高速轨迹
% ==========================================================

[trackTable, fitInfo] = selectRobustTrack( ...
    candidateTable, ...
    cfg, ...
    derived);

if fitInfo.valid

    trackTable = unwrapTrackVelocity( ...
        trackTable, ...
        derived.vMax, ...
        fitInfo.speed, ...
        cfg);

    validUnwrapped = ...
        isfinite( ...
        trackTable.UnwrappedVelocity_mps);

    if any(validUnwrapped)

        velocityError = ...
            trackTable.UnwrappedVelocity_mps( ...
            validUnwrapped) ...
            - cfg.measuredSpeed;

        fitInfo.meanUnwrappedSpeed = ...
            mean( ...
            trackTable.UnwrappedVelocity_mps( ...
            validUnwrapped));

        fitInfo.unwrapSpeedStd = ...
            std( ...
            trackTable.UnwrappedVelocity_mps( ...
            validUnwrapped));

        fitInfo.unwrapSpeedMae = ...
            mean(abs(velocityError));

        fitInfo.unwrapSpeedRmse = ...
            sqrt(mean(velocityError.^2));

    else

        fitInfo.meanUnwrappedSpeed = NaN;
        fitInfo.unwrapSpeedStd = NaN;
        fitInfo.unwrapSpeedMae = NaN;
        fitInfo.unwrapSpeedRmse = NaN;
    end

    fprintf('\n========================================\n');
    fprintf('高速目标轨迹拟合结果\n');
    fprintf('轨迹点数量：%d\n', height(trackTable));
    fprintf('表观径向速度：%.2f m/s\n', fitInfo.speed);
    fprintf('拟合距离截距：%.3f m\n', fitInfo.intercept);
    fprintf('距离拟合RMSE：%.3f m\n', fitInfo.rmse);
    fprintf('实测速度：%.5f m/s\n', ...
        cfg.measuredSpeed);
    fprintf('解模糊平均速度：%.2f m/s\n', ...
        fitInfo.meanUnwrappedSpeed);
    fprintf('解模糊速度标准差：%.2f m/s\n', ...
        fitInfo.unwrapSpeedStd);
    fprintf('解模糊速度相对实测速度MAE：%.2f m/s\n', ...
        fitInfo.unwrapSpeedMae);
    fprintf('解模糊速度相对实测速度RMSE：%.2f m/s\n', ...
        fitInfo.unwrapSpeedRmse);
    fprintf('========================================\n');

    disp(trackTable);

else
    warning( ...
        ['没有找到满足当前约束的连续高速轨迹。' ...
         '请适当降低candidateThresholdDb，' ...
         '或增大trackTolerance。']);
end

