%% =========================================================
%  14. 使用枪击前数据建立背景
% ==========================================================

% 每个距离单元的逐Chirp背景
rangeBackgroundDb = median( ...
    backgroundData.rangeTimeDb, ...
    2, ...
    'omitnan');

% 逐Chirp距离图仍采用原来的dB域背景增强，仅用于Figure 2显示
rangeTimeEnhanced = ...
    targetData.rangeTimeDb ...
    - rangeBackgroundDb;

% =========================================================
% 完整二维RD功率背景增强
%
% 1. 每个背景窗口先得到线性二维RD功率：
%       P(r,v,w) = sum_rx |X(r,v,w,rx)|^2
%
% 2. 对固定的距离-速度单元沿背景窗口维取中位数：
%       P_bg(r,v) = median_w P_bgWindow(r,v,w)
%
% 3. 目标窗口与背景功率作比值并转换为dB：
%       E(r,v,w) = 10log10(P_target / P_bg)
% =========================================================

powerFloor = single(1e-12);

% 完整二维RD线性功率背景：距离 × 有模糊速度
rdBackgroundPower = median( ...
    backgroundData.rdPowerCube, ...
    3, ...
    'omitnan');

% 目标帧完整二维RD功率相对背景的增强量
% 维度：距离 × 有模糊速度 × 窗口
rdEnhancedDb = ...
    10 * log10( ...
        (targetData.rdPowerCube + powerFloor) ...
        ./ (rdBackgroundPower + powerFloor));

% 只在指定的高速有模糊速度区域内进行压缩。
% 先完成每个距离-速度单元的背景增强，再沿速度维取最大值。
highSpeedEnhancedCube = ...
    rdEnhancedDb(:, derived.highSpeedMask, :);

[highSpeedEnhanced, maxVelocityIdx] = max( ...
    highSpeedEnhancedCube, ...
    [], ...
    2);

% max后维度为：距离 × 1 × 窗口，恢复为：距离 × 窗口
highSpeedEnhanced = reshape( ...
    highSpeedEnhanced, ...
    cfg.rangeFftSize, ...
    []);

maxVelocityIdx = reshape( ...
    maxVelocityIdx, ...
    cfg.rangeFftSize, ...
    []);

% 保存每个距离单元在背景增强后取得最大值时的有模糊速度
highSpeedVelocityMap = nan( ...
    size(highSpeedEnhanced), ...
    'single');

for windowIdx = 1:size(highSpeedEnhanced, 2)
    highSpeedVelocityMap(:, windowIdx) = single( ...
        derived.selectedVelocityAxis( ...
        maxVelocityIdx(:, windowIdx)));
end

