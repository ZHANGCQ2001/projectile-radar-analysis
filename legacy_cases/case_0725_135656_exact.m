%% =========================================================
%  局部函数：处理一个连续物理帧区间
% ==========================================================

function output = processFrameRange( ...
        fid, ...
        frameStart, ...
        frameEnd, ...
        cfg, ...
        derived)

    numFrames = ...
        frameEnd - frameStart + 1;

    totalChirps = ...
        numFrames * cfg.numChirpsPerFrame;

    totalWindows = ...
        numFrames * derived.windowsPerFrame;

    output.rangeTimeDb = nan( ...
        cfg.rangeFftSize, ...
        totalChirps, ...
        'single');

    output.chirpTimeMs = nan( ...
        1, totalChirps);

    % 完整二维RD线性功率：
    % 距离 × 有模糊速度 × 窗口
    output.rdPowerCube = nan( ...
        cfg.rangeFftSize, ...
        cfg.dopplerFftSize, ...
        totalWindows, ...
        'single');

    output.windowTimeMs = nan( ...
        1, totalWindows);

    output.windowPhysicalFrame = nan( ...
        1, totalWindows);

    output.windowIndexInFrame = nan( ...
        1, totalWindows);

    output.numFrames = numFrames;

    chirpColumn = 1;
    windowColumn = 1;

    for frameIdx = frameStart:frameEnd

        fprintf('  正在处理物理帧 %d / %d\n', ...
            frameIdx, frameEnd);

        byteOffset = ...
            (frameIdx - 1) ...
            * cfg.bytesPerFrame;

        seekStatus = ...
            fseek(fid, byteOffset, 'bof');

        if seekStatus ~= 0
            error('无法跳转到物理帧%d。', frameIdx);
        end

        rawData = fread( ...
            fid, ...
            cfg.uint16PerFrame, ...
            'uint16=>double');

        if numel(rawData) < cfg.uint16PerFrame
            error('物理帧%d数据不完整。', frameIdx);
        end

        negativeMask = ...
            rawData >= 2^15;

        rawData(negativeMask) = ...
            rawData(negativeMask) - 2^16;

        adcComplex = complex( ...
            rawData(1:2:end), ...
            rawData(2:2:end));

        % 原始排列：
        % Sample × RX × Chirp
        adcComplex = reshape( ...
            adcComplex, ...
            cfg.numSamples, ...
            cfg.numRx, ...
            cfg.numChirpsPerFrame);

        % 转换为：
        % Sample × Chirp × RX
        adcFrame = permute( ...
            adcComplex, ...
            [1, 3, 2]);

        adcFrame = single(adcFrame);

        %% 逐Chirp距离FFT

        rangeFftAll = fft( ...
            adcFrame .* derived.rangeWindow, ...
            cfg.rangeFftSize, ...
            1);

        rangeAmplitude = sum( ...
            abs(rangeFftAll), ...
            3);

        rangeAmplitudeDb = ...
            20 * log10( ...
                rangeAmplitude ...
                + single(1e-6));

        chirpColumnEnd = ...
            chirpColumn ...
            + cfg.numChirpsPerFrame - 1;

        chirpColumns = ...
            chirpColumn:chirpColumnEnd;

        output.rangeTimeDb(:, chirpColumns) = ...
            rangeAmplitudeDb;

        relativeFrameIdx = ...
            frameIdx - frameStart;

        output.chirpTimeMs(chirpColumns) = ...
            (relativeFrameIdx ...
            * cfg.framePeriod ...
            + (0:cfg.numChirpsPerFrame - 1) ...
            * cfg.chirpPeriod) ...
            * 1e3;

        chirpColumn = ...
            chirpColumnEnd + 1;

        %% 每个窗口计算RD图

        for localWindowIdx = ...
                1:derived.windowsPerFrame

            chirpStart = ...
                (localWindowIdx - 1) ...
                * cfg.winStep + 1;

            chirpEnd = ...
                chirpStart ...
                + cfg.winSize - 1;

            chirpIndices = ...
                chirpStart:chirpEnd;

            adcWindow = ...
                adcFrame(:, chirpIndices, :);

            % 慢时间复数去均值
            adcWindow = ...
                adcWindow ...
                - mean(adcWindow, 2);

            rangeFftWindow = fft( ...
                adcWindow ...
                .* derived.rangeWindow, ...
                cfg.rangeFftSize, ...
                1);

            rangeDoppler = fftshift( ...
                fft( ...
                    rangeFftWindow ...
                    .* derived.dopplerWindow, ...
                    cfg.dopplerFftSize, ...
                    2), ...
                2);

            % 对所有接收通道进行功率非相干累加。
            % 保留线性功率，不在这里转换为dB，也不提前压缩速度维。
            rdPower = sum( ...
                abs(rangeDoppler).^2, ...
                3);

            output.rdPowerCube( ...
                :, :, windowColumn) = ...
                single(rdPower);

            windowCenterChirp = ...
                (chirpStart - 1) ...
                + (cfg.winSize - 1) / 2;

            output.windowTimeMs( ...
                windowColumn) = ...
                (relativeFrameIdx ...
                * cfg.framePeriod ...
                + windowCenterChirp ...
                * cfg.chirpPeriod) ...
                * 1e3;

            output.windowPhysicalFrame( ...
                windowColumn) = ...
                frameIdx;

            output.windowIndexInFrame( ...
                windowColumn) = ...
                localWindowIdx;

            windowColumn = ...
                windowColumn + 1;
        end
    end
end

%% =========================================================
%  局部函数：提取每个窗口的多个局部候选点
% ==========================================================

function candidateTable = ...
        extractHighSpeedCandidates( ...
        highSpeedEnhanced, ...
        highSpeedVelocityMap, ...
        targetData, ...
        rangeAxis, ...
        cfg)

    globalWindow = [];
    physicalFrame = [];
    windowInFrame = [];
    timeMs = [];
    rangeM = [];
    aliasedVelocity = [];
    relativeStrength = [];
    rangeBin = [];

    rangeGate = ...
        rangeAxis(:) >= cfg.candidateRangeMin ...
        & rangeAxis(:) <= cfg.candidateRangeMax;

    numWindows = ...
        size(highSpeedEnhanced, 2);

    for windowIdx = 1:numWindows

        profile = double( ...
            highSpeedEnhanced(:, windowIdx));

        profileSmooth = movmean( ...
            profile, ...
            cfg.rangeSmoothBins, ...
            'omitnan');

        profileSmooth(~rangeGate) = -Inf;

        numBins = numel(profileSmooth);
        
        validBins = find(rangeGate);
        
        if numel(validBins) < 3
            continue;
        end
        
        firstValidBin = validBins(1);
        lastValidBin = validBins(end);
        
        isLocalPeak = false(numBins, 1);
        
        % 不允许候选点位于距离搜索区的两个边界
        innerBins = ...
            (firstValidBin + 1):(lastValidBin - 1);
        
        isLocalPeak(innerBins) = ...
            profileSmooth(innerBins) ...
            >= profileSmooth(innerBins - 1) ...
            & profileSmooth(innerBins) ...
            > profileSmooth(innerBins + 1);
        
        peakIndices = find( ...
            isLocalPeak ...
            & profileSmooth ...
            >= cfg.candidateThresholdDb);

        if isempty(peakIndices)
            continue;
        end

        [~, sortOrder] = sort( ...
            profileSmooth(peakIndices), ...
            'descend');

        peakIndices = ...
            peakIndices(sortOrder);

        selectedIndices = [];

        for idx = 1:numel(peakIndices)

            currentBin = ...
                peakIndices(idx);

            currentRange = ...
                rangeAxis(currentBin);

            if isempty(selectedIndices)

                isSeparated = true;

            else

                selectedRanges = ...
                    rangeAxis(selectedIndices);

                isSeparated = all( ...
                    abs( ...
                    selectedRanges ...
                    - currentRange) ...
                    >= cfg.minCandidateSeparation);
            end

            if isSeparated

                selectedIndices(end + 1) = ...
                    currentBin; %#ok<AGROW>

                if numel(selectedIndices) ...
                        >= cfg.maxCandidatesPerWindow
                    break;
                end
            end
        end

        for idx = 1:numel(selectedIndices)

            currentBin = ...
                selectedIndices(idx);

            currentVelocity = ...
                highSpeedVelocityMap( ...
                currentBin, ...
                windowIdx);

            if ~isfinite(currentVelocity)
                continue;
            end

            globalWindow(end + 1, 1) = ...
                windowIdx; %#ok<AGROW>

            physicalFrame(end + 1, 1) = ...
                targetData.windowPhysicalFrame( ...
                windowIdx); %#ok<AGROW>

            windowInFrame(end + 1, 1) = ...
                targetData.windowIndexInFrame( ...
                windowIdx); %#ok<AGROW>

            timeMs(end + 1, 1) = ...
                targetData.windowTimeMs( ...
                windowIdx); %#ok<AGROW>

            rangeM(end + 1, 1) = ...
                rangeAxis(currentBin); %#ok<AGROW>

            aliasedVelocity(end + 1, 1) = ...
                currentVelocity; %#ok<AGROW>

            relativeStrength(end + 1, 1) = ...
                profileSmooth(currentBin); %#ok<AGROW>

            rangeBin(end + 1, 1) = ...
                currentBin; %#ok<AGROW>
        end
    end

    candidateTable = table( ...
        globalWindow, ...
        physicalFrame, ...
        windowInFrame, ...
        timeMs, ...
        rangeM, ...
        aliasedVelocity, ...
        relativeStrength, ...
        rangeBin, ...
        'VariableNames', { ...
            'GlobalWindow', ...
            'PhysicalFrame', ...
            'WindowInFrame', ...
            'Time_ms', ...
            'Range_m', ...
            'AliasedVelocity_mps', ...
            'RelativeStrength_dB', ...
            'RangeBin'});
end

%% =========================================================
%  局部函数：使用鲁棒直线模型筛选连续轨迹
% ==========================================================

function [trackTable, fitInfo] = ...
        selectRobustTrack( ...
        candidateTable, ...
        cfg, ...
        derived)

    trackTable = table();

    fitInfo.valid = false;
    fitInfo.speed = NaN;
    fitInfo.intercept = NaN;
    fitInfo.rmse = NaN;

    if isempty(candidateTable)
        return;
    end

    validMask = ...
        candidateTable.Time_ms ...
        >= cfg.trackStartTimeMs;

    candidates = ...
        candidateTable(validMask, :);

    if height(candidates) < 2
        return;
    end

    numCandidates = ...
        height(candidates);

    bestSelection = [];
    bestCount = 0;
    bestMetric = -Inf;

    for firstIdx = 1:numCandidates - 1

        for secondIdx = ...
                firstIdx + 1:numCandidates

            if candidates.GlobalWindow(firstIdx) ...
                    == candidates.GlobalWindow(secondIdx)
                continue;
            end

            time1 = ...
                candidates.Time_ms(firstIdx) ...
                * 1e-3;

            time2 = ...
                candidates.Time_ms(secondIdx) ...
                * 1e-3;

            deltaTime = ...
                time2 - time1;

            if deltaTime <= 0
                continue;
            end

            range1 = ...
                candidates.Range_m(firstIdx);

            range2 = ...
                candidates.Range_m(secondIdx);

            speed = ...
                (range2 - range1) ...
                / deltaTime;

            if speed < cfg.fitSpeedMin ...
                    || speed > cfg.fitSpeedMax
                continue;
            end

            intercept = ...
                range1 ...
                - speed * time1;

            [selectedRows, residuals, aliasResiduals] = ...
                selectNearestPerWindow( ...
                candidates, ...
                speed, ...
                intercept, ...
                cfg.trackTolerance, ...
                cfg, ...
                derived);

            currentCount = ...
                numel(selectedRows);

            if currentCount == 0
                continue;
            end

            currentStrength = sum( ...
                max( ...
                candidates.RelativeStrength_dB( ...
                selectedRows), ...
                0));

            meanResidual = mean(residuals);

            meanAliasResidual = mean(aliasResiduals);

            metric = ...
                currentCount * 100 ...
                + currentStrength ...
                - meanResidual * 20 ...
                - 0.20 * meanAliasResidual;

            if currentCount > bestCount ...
                    || (currentCount == bestCount ...
                    && metric > bestMetric)

                bestCount = ...
                    currentCount;

                bestMetric = ...
                    metric;

                bestSelection = ...
                    selectedRows;
            end
        end
    end

    if bestCount < cfg.minTrackWindows
        return;
    end

    selectedRows = ...
        bestSelection;

    % 迭代重新拟合并重新选择每个窗口的最近候选
    for iteration = 1:4

        selectedTime = ...
            candidates.Time_ms( ...
            selectedRows) * 1e-3;

        selectedRange = ...
            candidates.Range_m( ...
            selectedRows);

        fitPolynomial = polyfit( ...
            selectedTime, ...
            selectedRange, ...
            1);

        speed = ...
            fitPolynomial(1);

        intercept = ...
            fitPolynomial(2);

        if speed < cfg.fitSpeedMin ...
                || speed > cfg.fitSpeedMax
            return;
        end

        [newSelection, ~, ~] = ...
            selectNearestPerWindow( ...
            candidates, ...
            speed, ...
            intercept, ...
            cfg.trackTolerance, ...
            cfg, ...
            derived);

        if isequal( ...
                sort(newSelection), ...
                sort(selectedRows))
            break;
        end

        selectedRows = ...
            newSelection;

        if numel(selectedRows) ...
                < cfg.minTrackWindows
            return;
        end
    end

    trackTable = ...
        candidates(selectedRows, :);

    trackTable = sortrows( ...
        trackTable, ...
        'Time_ms');

    fitPolynomial = polyfit( ...
        trackTable.Time_ms * 1e-3, ...
        trackTable.Range_m, ...
        1);

    fittedRange = polyval( ...
        fitPolynomial, ...
        trackTable.Time_ms * 1e-3);

    residual = ...
        trackTable.Range_m ...
        - fittedRange;

    trackTable.FittedRange_m = ...
        fittedRange;

    trackTable.FitResidual_m = ...
        residual;

    fitInfo.valid = true;
    fitInfo.speed = fitPolynomial(1);
    fitInfo.intercept = fitPolynomial(2);
    fitInfo.rmse = sqrt(mean(residual.^2));
end

%% =========================================================
%  局部函数：给定直线，每个窗口选择距离最近的候选
% ==========================================================

function [selectedRows, selectedResiduals, ...
        selectedAliasResiduals] = ...
        selectNearestPerWindow( ...
        candidates, ...
        speed, ...
        intercept, ...
        tolerance, ...
        cfg, ...
        derived)

    selectedRows = [];
    selectedResiduals = [];
    selectedAliasResiduals = [];

    uniqueWindows = unique( ...
        candidates.GlobalWindow, ...
        'stable');

    measuredAlias = ...
        wrapVelocity(cfg.measuredSpeed, derived.vMax);

    for idx = 1:numel(uniqueWindows)

        currentWindow = ...
            uniqueWindows(idx);

        rows = find( ...
            candidates.GlobalWindow ...
            == currentWindow);

        predictedRange = ...
            speed ...
            * candidates.Time_ms(rows) ...
            * 1e-3 ...
            + intercept;

        distanceResidual = abs( ...
            candidates.Range_m(rows) ...
            - predictedRange);

        validMask = ...
            distanceResidual <= tolerance;

        if ~any(validMask)
            continue;
        end

        validRows = rows(validMask);
        validDistanceResidual = ...
            distanceResidual(validMask);

        aliasResidual = ...
            circularVelocityDifference( ...
            candidates.AliasedVelocity_mps(validRows), ...
            measuredAlias, ...
            derived.velocityPeriod);

        strength = ...
            candidates.RelativeStrength_dB(validRows);

        combinedCost = ...
            (validDistanceResidual / tolerance).^2 ...
            + cfg.measuredAliasCostWeight ...
            * (aliasResidual ...
            / cfg.measuredAliasTolerance).^2 ...
            - cfg.trackStrengthCostWeight ...
            * max(strength, 0) ...
            / max(cfg.candidateThresholdDb, 1);

        [~, bestLocalIndex] = ...
            min(combinedCost);

        selectedRows(end + 1, 1) = ...
            validRows(bestLocalIndex); %#ok<AGROW>

        selectedResiduals(end + 1, 1) = ...
            validDistanceResidual(bestLocalIndex); %#ok<AGROW>

        selectedAliasResiduals(end + 1, 1) = ...
            aliasResidual(bestLocalIndex); %#ok<AGROW>
    end
end

function wrappedVelocity = ...
        wrapVelocity(velocity, vMax)

    period = 2 * vMax;

    wrappedVelocity = ...
        mod(velocity + vMax, period) ...
        - vMax;
end

function difference = ...
        circularVelocityDifference( ...
        velocity1, ...
        velocity2, ...
        period)

    directDifference = ...
        abs(velocity1 - velocity2);

    difference = min( ...
        directDifference, ...
        period - directDifference);
end

%% =========================================================
%  局部函数：基于实测速度先验的全局速度解模糊
% ==========================================================

function trackTable = unwrapTrackVelocity( ...
        trackTable, ...
        vMax, ...
        referenceSpeed, ...
        cfg)

    % =========================================================
    % 实测速度先验辅助的全局速度解模糊
    %
    % 对每个轨迹点构造：
    %   v(i,k) = v_alias(i) + k * 2Vmax
    %
    % 动态规划同时考虑：
    %   1. 与实测速度的偏差；
    %   2. 与距离拟合速度的偏差；
    %   3. 相邻点之间的速度连续性。
    % =========================================================

    ambiguityPeriod = ...
        2 * vMax;

    ambiguityCandidates = ...
        cfg.ambiguityNumberMin: ...
        cfg.ambiguityNumberMax;

    aliasedVelocity = ...
        double( ...
        trackTable.AliasedVelocity_mps(:));

    numPoints = ...
        numel(aliasedVelocity);

    numStates = ...
        numel(ambiguityCandidates);

    possibleVelocity = ...
        aliasedVelocity ...
        + ambiguityPeriod ...
        * ambiguityCandidates;

    validMask = ...
        possibleVelocity ...
        >= cfg.unwrapSpeedMin ...
        & possibleVelocity ...
        <= cfg.unwrapSpeedMax;

    measuredCost = ...
        cfg.unwrapMeasuredWeight ...
        * ((possibleVelocity ...
        - cfg.measuredSpeed) ...
        / cfg.measuredSpeedStd).^2;

    fitCost = ...
        cfg.unwrapFitWeight ...
        * ((possibleVelocity ...
        - referenceSpeed) ...
        / cfg.distanceFitSpeedStd).^2;

    localCost = ...
        measuredCost + fitCost;

    localCost(~validMask) = Inf;

    accumulatedCost = ...
        inf(numPoints, numStates);

    previousState = ...
        zeros(numPoints, numStates);

    accumulatedCost(1, :) = ...
        localCost(1, :);

    for pointIdx = 2:numPoints

        for stateIdx = 1:numStates

            if ~isfinite( ...
                    localCost(pointIdx, stateIdx))
                continue;
            end

            transitionCost = ...
                cfg.unwrapContinuityWeight ...
                * ((possibleVelocity( ...
                pointIdx, stateIdx) ...
                - possibleVelocity( ...
                pointIdx - 1, :)) ...
                / cfg.unwrapContinuityStd).^2;

            totalPreviousCost = ...
                accumulatedCost( ...
                pointIdx - 1, :) ...
                + transitionCost;

            [minimumPreviousCost, ...
                bestPreviousState] = min( ...
                totalPreviousCost);

            accumulatedCost( ...
                pointIdx, stateIdx) = ...
                localCost(pointIdx, stateIdx) ...
                + minimumPreviousCost;

            previousState( ...
                pointIdx, stateIdx) = ...
                bestPreviousState;
        end
    end

    [bestFinalCost, bestState] = ...
        min(accumulatedCost(end, :));

    if ~isfinite(bestFinalCost)

        warning( ...
            ['没有找到满足当前速度范围的' ...
             '有效解模糊路径。']);

        trackTable.AmbiguityNumber = ...
            nan(numPoints, 1);

        trackTable.UnwrappedVelocity_mps = ...
            nan(numPoints, 1);

        trackTable.MeasuredSpeed_mps = ...
            repmat( ...
            cfg.measuredSpeed, ...
            numPoints, 1);

        return;
    end

    bestStateSequence = ...
        zeros(numPoints, 1);

    bestStateSequence(end) = ...
        bestState;

    for pointIdx = numPoints:-1:2

        bestStateSequence( ...
            pointIdx - 1) = ...
            previousState( ...
            pointIdx, ...
            bestStateSequence(pointIdx));
    end

    linearIndex = sub2ind( ...
        size(possibleVelocity), ...
        (1:numPoints).', ...
        bestStateSequence);

    unwrappedVelocity = ...
        possibleVelocity(linearIndex);

    ambiguityNumber = ...
        ambiguityCandidates( ...
        bestStateSequence).';

    trackTable.AmbiguityNumber = ...
        ambiguityNumber;

    trackTable.UnwrappedVelocity_mps = ...
        unwrappedVelocity;

    trackTable.MeasuredSpeed_mps = ...
        repmat( ...
        cfg.measuredSpeed, ...
        numPoints, 1);

    trackTable.MeasuredSpeedResidual_mps = ...
        unwrappedVelocity ...
        - cfg.measuredSpeed;

    trackTable.DistanceFitSpeedResidual_mps = ...
        unwrappedVelocity ...
        - referenceSpeed;

    trackTable.GlobalUnwrapPathCost = ...
        repmat( ...
        bestFinalCost, ...
        numPoints, 1);
end

%% =========================================================
%  局部函数：分物理帧绘制二维图
% ==========================================================

function ax = drawSegmentedMap( ...
        timeAxisMs, ...
        rangeAxis, ...
        mapData, ...
        columnsPerFrame, ...
        numFrames, ...
        figureName, ...
        titleText, ...
        rangeLimits, ...
        colorLimits)

    fig = figure( ...
        'Name', figureName, ...
        'Color', 'w');

    ax = axes(fig);

    hold(ax, 'on');

    totalColumns = ...
        size(mapData, 2);

    for localFrameIdx = 1:numFrames

        firstColumn = ...
            (localFrameIdx - 1) ...
            * columnsPerFrame + 1;

        lastColumn = min( ...
            localFrameIdx ...
            * columnsPerFrame, ...
            totalColumns);

        if firstColumn > totalColumns
            break;
        end

        columns = ...
            firstColumn:lastColumn;

        imagesc( ...
            ax, ...
            timeAxisMs(columns), ...
            rangeAxis, ...
            mapData(:, columns));
    end

    hold(ax, 'off');

    ax.YDir = 'normal';
    ax.Box = 'on';

    xlabel(ax, 'Time (ms)');
    ylabel(ax, 'Range (m)');
    title(ax, titleText);

    ylim(ax, rangeLimits);

    finiteTime = ...
        timeAxisMs(isfinite(timeAxisMs));

    if ~isempty(finiteTime)

        timeMargin = 0.1;

        xlim(ax, ...
            [min(finiteTime) - timeMargin, ...
             max(finiteTime) + timeMargin]);
    end

    if ~isempty(colorLimits)
        caxis(ax, colorLimits);
    end

    colormap(ax, turbo);
    colorbar(ax);
end

%% =========================================================
%  局部函数：标记物理帧有效数据边界
% ==========================================================

function addFrameLines( ...
        ax, ...
        numFrames, ...
        framePeriod, ...
        activeDuration)

    hold(ax, 'on');

    for localFrameIdx = 1:numFrames

        frameStartMs = ...
            (localFrameIdx - 1) ...
            * framePeriod ...
            * 1e3;

        activeEndMs = ...
            frameStartMs ...
            + activeDuration ...
            * 1e3;

        xline( ...
            ax, ...
            activeEndMs, ...
            'w--', ...
            'LineWidth', 0.8);

        if localFrameIdx < numFrames

            nextFrameStartMs = ...
                localFrameIdx ...
                * framePeriod ...
                * 1e3;

            xline( ...
                ax, ...
                nextFrameStartMs, ...
                'w:', ...
                'LineWidth', 0.8);
        end
    end

    hold(ax, 'off');
end