%% =========================================================
%  10. 距离轴与速度轴
% ==========================================================

derived.rangeBinSpacing = ...
    cfg.c * cfg.adcSampleRate ...
    / (2 * cfg.slope * cfg.rangeFftSize);

derived.rangeAxis = ...
    (0:cfg.rangeFftSize - 1) ...
    * derived.rangeBinSpacing;

adcDuration = ...
    cfg.numSamples / cfg.adcSampleRate;

bandwidth = ...
    cfg.slope * adcDuration;

centerFreq = ...
    cfg.startFreq + bandwidth / 2;

derived.lambda = ...
    cfg.c / centerFreq;

derived.deltaV = ...
    derived.lambda ...
    / (2 * cfg.winSize * cfg.chirpPeriod);

derived.deltaVDisplay = ...
    derived.lambda ...
    / (2 * cfg.dopplerFftSize * cfg.chirpPeriod);

derived.velocityAxis = ...
    (-cfg.dopplerFftSize / 2 : cfg.dopplerFftSize / 2 - 1) ...
    * derived.deltaVDisplay;

derived.vMax = ...
    cfg.winSize / 2 * derived.deltaV;

derived.velocityPeriod = ...
    2 * derived.vMax;

derived.measuredAliasedSpeed = ...
    wrapVelocity(cfg.measuredSpeed, derived.vMax);

derived.highSpeedMask = ...
    abs(derived.velocityAxis) >= cfg.highSpeedMin;

derived.selectedVelocityAxis = ...
    derived.velocityAxis(derived.highSpeedMask);

derived.windowsPerFrame = ...
    floor( ...
        (cfg.numChirpsPerFrame - cfg.winSize) ...
        / cfg.winStep) + 1;

derived.rangeWindow = reshape( ...
    single(hann(cfg.numSamples)), ...
    cfg.numSamples, 1, 1);

derived.dopplerWindow = reshape( ...
    single(hann(cfg.winSize)).', ...
    1, cfg.winSize, 1);

if ~any(derived.highSpeedMask)
    error('高速速度门限过大，没有速度单元被保留。');
end

fprintf('距离单元间隔：%.4f m\n', ...
    derived.rangeBinSpacing);

fprintf('速度分辨率：%.3f m/s\n', ...
    derived.deltaV);

fprintf('最大不模糊速度：±%.3f m/s\n', ...
    derived.vMax);

fprintf('速度模糊周期：%.3f m/s\n', ...
    derived.velocityPeriod);

fprintf('实测速度：%.5f m/s\n', ...
    cfg.measuredSpeed);

fprintf('实测速度对应有模糊速度：%+.3f m/s\n', ...
