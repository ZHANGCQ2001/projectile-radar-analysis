cfg.unwrapFitWeight = 0.45;
cfg.unwrapContinuityWeight = 0.80;

% 模糊数搜索范围。
cfg.ambiguityNumberMin = -4;
cfg.ambiguityNumberMax = 8;

% 在距离轨迹关联阶段使用实测速度折叠值作为软约束。
cfg.measuredAliasTolerance = 60.0; % m/s
cfg.measuredAliasCostWeight = 0.30;
cfg.trackStrengthCostWeight = 0.10;

