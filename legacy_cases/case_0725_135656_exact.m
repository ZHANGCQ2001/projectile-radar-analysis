%  3. 轨迹筛选与速度拟合参数
% ==========================================================

% 拟合时允许的表观径向速度范围
cfg.fitSpeedMin = 300;             % m/s
cfg.fitSpeedMax = 700;             % m/s

% 候选点距拟合轨迹小于该值时视为内点
cfg.trackTolerance = 0.55;         % m

